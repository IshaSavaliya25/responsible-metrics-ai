def build_markdown_audit_report():
    import json

    def to_dict(val):
        if isinstance(val, dict):
            return val
        if isinstance(val, str):
            try:
                return json.loads(val)
            except Exception:
                return {}
        return {}

    nlp_d = to_dict(nlp_analysis)
    bib_d = to_dict(bibliometric_analysis)
    principle_d = to_dict(principle_analysis)
    gap_d = to_dict(research_gap_analysis)

    title_str = analysis_result.get("title") or analysis_result.get("filename") or "Research Paper"
    report_lines = [
        f"# ResponsibleMetrics AI: Evaluation Audit Report",
        f"**Paper Title:** {title_str}",
        f"**Analysis ID:** {analysis_result.get('id')} | **Filename:** {analysis_result.get('filename')}",
        f"**Generated On:** {analysis_result.get('created_at', 'N/A')}",
        "",
        "## Executive Summary Scores",
        f"- **Responsible Metrics Score:** {responsible_score:.2f}%",
        f"- **Principle Compliance Score:** {compliance_score:.2f}%",
        f"- **Research Novelty Level:** {novelty_level}",
        f"- **Average Literature Similarity:** {average_similarity:.4f}",
        "",
        "## 1. Natural Language Processing (NLP) Findings",
        f"- **Extracted Keywords:** {', '.join([k if isinstance(k, str) else k.get('keyword', '') for k in nlp_d.get('keywords', [])[:8]])}",
        f"- **Research Problems Identified:**",
    ]
    for p in (nlp_d.get("research_problems") or ["None identified"]):
        report_lines.append(f"  - {p}")
    report_lines.append("- **Contributions:**")
    for c in (nlp_d.get("research_contributions") or ["None identified"]):
        report_lines.append(f"  - {c}")
    report_lines.append("- **Key Findings:**")
    for f in (nlp_d.get("key_findings") or ["None identified"]):
        report_lines.append(f"  - {f}")

    oa_val = bib_d.get("open_access")
    oa_str = oa_val.get("is_oa", "Unknown") if isinstance(oa_val, dict) else "Unknown"

    report_lines.extend([
        "",
        "## 2. Bibliometric Profile (OpenAlex Integration)",
        f"- **Citations (Cited by Count):** {bib_d.get('citation_count', 'N/A')}",
        f"- **Publication Year:** {bib_d.get('publication_year', 'N/A')}",
        f"- **Source / Journal:** {bib_d.get('journal', 'N/A')}",
        f"- **Open Access:** {oa_str}",
        "",
        "## 3. Responsible Research Assessment (Leiden & DORA Principles)",
    ])

    practices = principle_d.get("responsible_practices", [])
    if practices:
        report_lines.append("### Adherent Responsible Practices:")
        for pr in practices:
            report_lines.append(f"- [x] **{pr.get('category', 'Practice')}**: {pr.get('principle', '')}")
    else:
        report_lines.append("- No explicit adherence statements detected.")

    misuses = principle_d.get("potential_misuse", [])
    if misuses:
        report_lines.append("\n### Detected Indicator Misuse / Red Flags:")
        for m in misuses:
            report_lines.append(f"- [!] **[{m.get('severity', 'WARNING').upper()}] {m.get('message', '')}**")
            if m.get("explanation"):
                report_lines.append(f"  - *Explanation:* {m.get('explanation')}")
            if m.get("remediation"):
                report_lines.append(f"  - *Remediation:* {m.get('remediation')}")

    recs = principle_d.get("recommendations", [])
    if recs:
        report_lines.append("\n### Actionable Recommendations:")
        for r in recs:
            report_lines.append(f"1. {r}")

    report_lines.extend([
        "",
        "## 4. Research Gap & Novelty Analysis",
        f"- **Novelty Rating:** {novelty_level}",
        f"- **Gap Summary:** {gap_d.get('potential_gap', 'N/A')}",
        "",
        "---",
        "*Report certified by ResponsibleMetrics AI Framework for Responsible Bibliometrics.*"
    ])
    return "\n".join(report_lines)

